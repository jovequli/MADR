"""Metric-based symptom classification and parameter-trial hypotheses.

Available metrics drive deterministic labels and heuristic priorities. The LLM
may accept or revise candidate actions using the supplied evidence. The actual
recommendations are generated by _generate_recommendations; their visibility
is controlled by the calling prompt projection."""

import math
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any


# ============================================================================
# Data structures
# ============================================================================

@dataclass
class DiagnosisResult:
    """Diagnostic symptoms and ordered parameter hypotheses.

    Responsibility fields are normalized heuristic priority weights, not measured
    causal contributions. Severity ranks suggestions; reasoning describes the
    available evidence, and improvement_trend compares supplied NSE records."""
    primary_issue: str = "none"
    severity: str = "minor"
    severity_score: float = 0.0
    vic_responsibility: float = 0.0
    routing_responsibility: float = 0.0
    upstream_responsibility: float = 0.0
    reasoning: str = ""
    recommendations: List[Dict[str, Any]] = field(default_factory=list)
    improvement_trend: str = "stagnant"
    diagnostic_status: str = "complete"
    unavailable_metrics: List[str] = field(default_factory=list)
    issue_status: Dict[str, str] = field(default_factory=dict)


# ============================================================================
# Finite-value helpers
# ============================================================================

def _safe_float(v, default=0.0) -> float:
    """Return a finite float, or the default for missing/nonfinite values."""
    if v is None or isinstance(v, bool):
        return default
    try:
        f = float(v)
        if math.isnan(f) or math.isinf(f):
            return default
        return f
    except (ValueError, TypeError):
        return default


# ============================================================================
# Diagnostic entry point
# ============================================================================

def diagnose_round(
    metrics: Dict[str, Any],
    prev_metrics: Optional[Dict[str, Any]] = None,
    context: Optional[Dict[str, Any]] = None,
) -> DiagnosisResult:
    """Classify one measured result and generate conditional parameter hypotheses.

    metrics contains NSE and any available diagnostic signatures. prev_metrics
    optionally supplies the previous result. context supplies headwater status
    and upstream quality. The returned DiagnosisResult separates symptoms,
    heuristic priorities, and recommendations."""
    try:
        if context is None:
            context = {}
        is_headwater = context.get("is_headwater", True)
        upstream_quality = context.get("upstream_quality", "good")

        # Read available metrics
        metric_keys = ("NSE", "PBIAS", "peak_ratio", "lowflow_ratio",
                       "peak_timing_bias_days", "recession_k_ratio",
                       "baseflow_index_bias_pct", "peak_magnitude_bias_pct")
        values = {key: _safe_float(metrics.get(key), None) for key in metric_keys}
        unavailable = [key for key in metric_keys if values[key] is None]
        nse, pbias, peak_ratio, lowflow_ratio, peak_timing, recession_k, baseflow_bias, peak_mag_bias = (
            values[key] for key in metric_keys)
        issue_status = _issue_status(pbias, peak_timing, recession_k, baseflow_bias, peak_ratio, lowflow_ratio)
        if nse is None:
            return DiagnosisResult(
                primary_issue="unknown", severity="unknown", improvement_trend="unknown",
                diagnostic_status="unavailable", unavailable_metrics=unavailable,
                issue_status={key: "unknown" for key in issue_status},
                reasoning="NSE unavailable; no physical responsibility or parameter action is inferred.",
            )

        # Step 1: Severity classification
        severity, severity_score = _classify_severity(nse)

        # Step 2: Primary symptom classification
        primary_issue = _classify_primary_issue(
            pbias, peak_timing, recession_k, baseflow_bias, peak_ratio, lowflow_ratio
        )

        # Step 3: Heuristic priority weights
        vic_resp, routing_resp, upstream_resp = _attribute_responsibility(
            primary_issue, is_headwater, upstream_quality
        )

        # Step 4: Describe the diagnostic evidence
        reasoning = _generate_reasoning(
            primary_issue, pbias, peak_timing, recession_k,
            baseflow_bias, vic_resp, routing_resp,
            peak_ratio=peak_ratio, lowflow_ratio=lowflow_ratio
        )

        # Step 5: Generate parameter hypotheses
        recommendations = _generate_recommendations(
            primary_issue, pbias, peak_ratio, lowflow_ratio,
            peak_timing, recession_k, baseflow_bias, peak_mag_bias,
            severity_score
        )

        # Step 6: Improvement trend
        improvement_trend = _assess_trend(nse, prev_metrics)
        if unavailable:
            reasoning += " Unavailable diagnostics: " + ", ".join(unavailable) + "; dependent rules skipped."

        return DiagnosisResult(
            primary_issue=primary_issue,
            severity=severity,
            severity_score=severity_score,
            vic_responsibility=vic_resp,
            routing_responsibility=routing_resp,
            upstream_responsibility=upstream_resp,
            reasoning=reasoning,
            recommendations=recommendations,
            improvement_trend=improvement_trend,
            diagnostic_status="partial" if unavailable else "complete",
            unavailable_metrics=unavailable,
            issue_status=issue_status,
        )

    except Exception as e:
        # Diagnostic fallback
        return DiagnosisResult(
            primary_issue="unknown", severity="unknown", improvement_trend="unknown",
            diagnostic_status="unavailable",
            reasoning=f"Diagnostic unavailable: {type(e).__name__}: {e}",
        )


# ============================================================================
# Step 1: Severity classification
# ============================================================================

def _classify_severity(nse: float) -> tuple:
    """Return the severity label and numerical priority score."""
    if nse == -999 or math.isnan(nse):
        return "severe", 1.0
    if nse > 0.65:
        # Minor: linear score in [0, 0.35]
        score = max(0.0, 1.0 - nse)  # nse=0.65 → score=0.35, nse=1.0 → score=0.0
        return "minor", score
    elif nse > 0.4:
        # Moderate: score in [0.35, 0.6]
        score = 1.0 - nse  # nse=0.4 → score=0.6, nse=0.65 → score=0.35
        return "moderate", score
    else:
        # Severe: score in [0.6, 1.0]
        score = min(1.0, 1.0 - nse)
        return "severe", score


# ============================================================================
# Step 2: Primary symptom classification
# ============================================================================

def _classify_primary_issue(
    pbias: float, peak_timing: float, recession_k: float,
    baseflow_bias: float, peak_ratio: float, lowflow_ratio: float
) -> str:
    """Classify available volume, timing, shape and low-flow/BFI symptoms.

    Thresholds are implemented below; a symptom does not identify its cause."""
    statuses = _issue_status(pbias, peak_timing, recession_k, baseflow_bias, peak_ratio, lowflow_ratio)
    issues = [name for name, status in statuses.items() if status == "issue"]
    if len(issues) > 1:
        return "combined"
    if issues:
        return issues[0]
    return "unknown" if "unknown" in statuses.values() else "none"


def _issue_status(pbias, peak_timing, recession_k, baseflow_bias, peak_ratio, lowflow_ratio):
    """Three-valued checks: no unavailable metric is interpreted as evidence of normality."""
    def any_issue(checks):
        if any(value is True for value in checks):
            return "issue"
        return "unknown" if any(value is None for value in checks) else "clear"

    return {
        "volume": any_issue([abs(pbias) > 10.0 if pbias is not None else None,
                             abs(peak_ratio - 1.0) > 0.15 if peak_ratio is not None else None]),
        "timing": any_issue([abs(peak_timing) > 2.0 if peak_timing is not None else None]),
        "shape": any_issue([recession_k < 0.7 or recession_k > 1.3 if recession_k is not None else None]),
        "baseflow": any_issue([abs(baseflow_bias) > 20.0 if baseflow_bias is not None else None,
                               abs(lowflow_ratio - 1.0) > 0.2 if lowflow_ratio is not None else None]),
    }


# ============================================================================
# Step 3: Heuristic priority weights
# ============================================================================

def _attribute_responsibility(
    primary_issue: str, is_headwater: bool, upstream_quality: str
) -> tuple:
    """Return normalized VIC, routing and upstream heuristic priorities.

    These are fixed, uncalibrated heuristic weights; they are not
    probabilities or established physical attribution. The implementation below
    defines the values for each symptom and upstream context."""
    if primary_issue in ("none", "unknown"):
        return 0.0, 0.0, 0.0

    ATTRIBUTION = {
        "volume":   (0.9, 0.1, 0.0),
        "timing":   (0.1, 0.9, 0.0),
        "shape":    (0.85, 0.15, 0.0),
        "baseflow": (0.8, 0.2, 0.0),
    }

    if primary_issue in ATTRIBUTION:
        vic, rout, up = ATTRIBUTION[primary_issue]
    elif primary_issue == "combined":
        if not is_headwater and upstream_quality in ("poor", "acceptable"):
            vic, rout, up = 0.3, 0.2, 0.5
        else:
            vic, rout, up = 0.5, 0.5, 0.0
    else:
        vic, rout, up = 0.33, 0.33, 0.34

    # Normalize weights
    total = vic + rout + up
    if total > 0:
        vic /= total
        rout /= total
        up /= total

    return round(vic, 2), round(rout, 2), round(up, 2)


# ============================================================================
# Step 4: Diagnostic description
# ============================================================================

def _generate_reasoning(
    primary_issue: str, pbias: float, peak_timing: float,
    recession_k: float, baseflow_bias: float,
    vic_resp: float, routing_resp: float,
    peak_ratio: Optional[float] = None, lowflow_ratio: Optional[float] = None,
) -> str:
    """Describe the evidence triggering the assigned symptom category.

    Category names and numerical priority weights are stable output fields.
    High-flow-day mismatch is not total-volume bias; low-flow-day mismatch and
    filtered-BFI fraction bias are not measurements of absolute baseflow.  Causes
    and parameter responses remain hypotheses, not facts established by a label.
    """
    if primary_issue == "unknown":
        return "Insufficient diagnostics to rule out an issue; no responsibility inferred from unavailable metrics."
    if primary_issue == "none":
        return "No configured classification threshold exceeded; this does not establish acceptable overall fit."

    facts = []
    if primary_issue in ("volume", "combined"):
        if pbias is not None and abs(pbias) > 10.0:
            direction = "too high" if pbias > 0 else "too low"
            facts.append(f"Scored total flow {direction} (PBIAS={pbias:.6g}%)")
        if peak_ratio is not None and abs(peak_ratio - 1.0) > 0.15:
            direction = "too high" if peak_ratio > 1 else "too low"
            facts.append(f"High-flow-day mean {direction} (peak_ratio={peak_ratio:.6g})")
        if primary_issue == "volume":
            if pbias is None:
                facts.append("PBIAS unavailable; total-volume direction unknown")
            elif abs(pbias) <= 10.0:
                facts.append(f"PBIAS={pbias:.6g}% is within the +/-10% volume threshold")
            facts.append("The historical volume bucket also covers high-flow-day mismatch")
    if primary_issue in ("timing", "combined") and peak_timing is not None and abs(peak_timing) > 2.0:
        direction = "too early" if peak_timing < 0 else "too late"
        facts.append(f"Matched peaks {direction} (timing_bias={peak_timing:.6g}d)")
    if primary_issue in ("shape", "combined") and recession_k is not None and (recession_k < 0.7 or recession_k > 1.3):
        direction = "faster" if recession_k > 1.3 else "slower"
        facts.append(f"Simulated recession {direction} (absolute log-decay-rate ratio={recession_k:.6g})")
    if primary_issue in ("baseflow", "combined"):
        if lowflow_ratio is not None and abs(lowflow_ratio - 1.0) > 0.2:
            direction = "too low" if lowflow_ratio < 1 else "too high"
            facts.append(f"Low-flow-day mean {direction} (lowflow_ratio={lowflow_ratio:.6g})")
        if baseflow_bias is not None and abs(baseflow_bias) > 20.0:
            direction = "too low" if baseflow_bias < 0 else "too high"
            facts.append(f"Filtered baseflow fraction {direction} (BFI relative bias={baseflow_bias:.6g}%)")
        if primary_issue == "baseflow":
            if baseflow_bias is None:
                facts.append("BFI unavailable; its direction cannot be inferred from low-flow ratio")
            elif abs(baseflow_bias) <= 20.0:
                facts.append(f"BFI relative bias={baseflow_bias:.6g}% is within the +/-20% threshold")
            facts.append("The historical baseflow bucket is not an absolute-baseflow diagnosis")

    if primary_issue == "combined":
        facts.append(f"Legacy heuristic priorities: VIC={vic_resp:.0%}, Routing={routing_resp:.0%}")
    text = "; ".join(facts) if facts else "No triggering metric supplied to the reasoning formatter"
    return text + ". Process causes and parameter responses remain hypotheses to test."


# ============================================================================
# Step 5: Generate parameter hypotheses
# ============================================================================

def _generate_recommendations(
    primary_issue: str, pbias: float, peak_ratio: float,
    lowflow_ratio: float, peak_timing: float, recession_k: float,
    baseflow_bias: float, peak_mag_bias: float, severity_score: float
) -> List[Dict]:
    """
    Generate parameter adjustment recommendations based on diagnosis.

    Each rec: {param, direction, magnitude, confidence, reason, category}
    category: "vic" or "routing"
    """
    recs = []

    # === VIC recommendations ===

    # Observed high-flow-day mean too high → trial decreasing binfilt
    if peak_ratio is not None and peak_ratio > 1.05:
        mag = "large" if peak_ratio > 1.2 else "medium" if peak_ratio > 1.1 else "small"
        recs.append({
            "param": "binfilt", "direction": "decrease", "magnitude": mag,
            "confidence": min(0.95, 0.5 + abs(peak_ratio - 1.0)),
            "reason": f"High-flow-day mean ratio={peak_ratio:.6g}>1.05; trial binfilt decrease to test a high-flow response (not a matched-peak-height diagnosis)",
            "category": "vic"
        })

    # Observed high-flow-day mean too low → trial increasing binfilt
    if peak_ratio is not None and peak_ratio < 0.95:
        mag = "large" if peak_ratio < 0.8 else "medium" if peak_ratio < 0.9 else "small"
        recs.append({
            "param": "binfilt", "direction": "increase", "magnitude": mag,
            "confidence": min(0.95, 0.5 + abs(peak_ratio - 1.0)),
            "reason": f"High-flow-day mean ratio={peak_ratio:.6g}<0.95; trial binfilt increase to test a high-flow response (not a matched-peak-height diagnosis)",
            "category": "vic"
        })

    # Low flow too low → increase Ds/soil_d3
    if lowflow_ratio is not None and lowflow_ratio < 0.9:
        recs.append({
            "param": "Ds", "direction": "increase", "magnitude": "medium",
            "confidence": 0.7,
            "reason": f"Low-flow-day mean ratio={lowflow_ratio:.6g}<0.9; trial Ds increase to test the low-flow response; absolute baseflow is not identified",
            "category": "vic"
        })
        recs.append({
            "param": "soil_d3", "direction": "increase", "magnitude": "small",
            "confidence": 0.6,
            "reason": f"Low-flow-day mean ratio={lowflow_ratio:.6g}<0.9; trial soil_d3 increase as a storage hypothesis; the low-flow response is not guaranteed",
            "category": "vic"
        })

    # Low flow too high → decrease Ds
    if lowflow_ratio is not None and lowflow_ratio > 1.1:
        recs.append({
            "param": "Ds", "direction": "decrease", "magnitude": "medium",
            "confidence": 0.7,
            "reason": f"Low-flow-day mean ratio={lowflow_ratio:.6g}>1.1; trial Ds decrease to test the low-flow response; absolute baseflow is not identified",
            "category": "vic"
        })

    # PBIAS too wet → increase soil_d2 storage
    if pbias is not None and pbias > 10.0:
        recs.append({
            "param": "soil_d2", "direction": "increase", "magnitude": "medium",
            "confidence": 0.75,
            "reason": f"PBIAS={pbias:.6g}%>10: scored total flow too high; trial soil_d2 increase as a storage hypothesis, not an identified cause",
            "category": "vic"
        })

    # PBIAS too dry → decrease soil_d2
    if pbias is not None and pbias < -10.0:
        recs.append({
            "param": "soil_d2", "direction": "decrease", "magnitude": "medium",
            "confidence": 0.75,
            "reason": f"PBIAS={pbias:.6g}%<-10: scored total flow too low; trial soil_d2 decrease as a storage hypothesis, not an identified cause",
            "category": "vic"
        })

    # Recession too fast → increase soil_d3 + Ws
    if recession_k is not None and recession_k > 1.3:
        recs.append({
            "param": "soil_d3", "direction": "increase", "magnitude": "medium",
            "confidence": 0.8,
            "reason": f"Recession log-decay-rate ratio={recession_k:.6g}>1.3: simulated recession faster; trial soil_d3 increase to test storage effects",
            "category": "vic"
        })
        recs.append({
            "param": "Ws", "direction": "increase", "magnitude": "small",
            "confidence": 0.6,
            "reason": "Simulated recession faster; trial Ws increase to test nonlinear-baseflow-threshold effects; recession response is conditional",
            "category": "vic"
        })

    # Recession too slow → decrease soil_d3 + increase Ds
    if recession_k is not None and recession_k < 0.7:
        recs.append({
            "param": "soil_d3", "direction": "decrease", "magnitude": "medium",
            "confidence": 0.8,
            "reason": f"Recession log-decay-rate ratio={recession_k:.6g}<0.7: simulated recession slower; trial soil_d3 decrease to test storage effects",
            "category": "vic"
        })
        recs.append({
            "param": "Ds", "direction": "increase", "magnitude": "small",
            "confidence": 0.6,
            "reason": "Simulated recession slower; trial Ds increase to test drainage effects; recession response is conditional",
            "category": "vic"
        })

    # A low filtered baseflow fraction motivates a conditional soil_d3 trial.
    if baseflow_bias is not None and baseflow_bias < -20.0:
        recs.append({
            "param": "soil_d3", "direction": "increase", "magnitude": "medium",
            "confidence": 0.75,
            "reason": f"Filtered-BFI relative bias={baseflow_bias:.6g}%<-20: baseflow fraction too low; trial soil_d3 increase, without inferring absolute baseflow or a guaranteed response",
            "category": "vic"
        })

    # === Routing recommendations ===

    # Peak too early → decrease velocity
    if peak_timing is not None and peak_timing < -2.0:
        mag = "large" if peak_timing < -5 else "medium" if peak_timing < -3 else "small"
        recs.append({
            "param": "velocity", "direction": "decrease", "magnitude": mag,
            "confidence": min(0.9, 0.5 + abs(peak_timing) * 0.1),
            "reason": f"Matched-peak timing bias={peak_timing:.6g}d: peaks early; trial velocity decrease to test a delay, not proof velocity is the cause",
            "category": "routing"
        })

    # Peak too late → increase velocity
    if peak_timing is not None and peak_timing > 2.0:
        mag = "large" if peak_timing > 5 else "medium" if peak_timing > 3 else "small"
        recs.append({
            "param": "velocity", "direction": "increase", "magnitude": mag,
            "confidence": min(0.9, 0.5 + abs(peak_timing) * 0.1),
            "reason": f"Matched-peak timing bias={peak_timing:.6g}d: peaks late; trial velocity increase to test an advance, not proof velocity is the cause",
            "category": "routing"
        })

    # Matched peak height high, scored total flow near observation → diffusivity trial
    if peak_mag_bias is not None and pbias is not None and peak_mag_bias > 20.0 and abs(pbias) < 10.0:
        recs.append({
            "param": "diffusivity", "direction": "increase", "magnitude": "small",
            "confidence": 0.7,
            "reason": f"Matched-peak height bias={peak_mag_bias:.6g}%>20 and |PBIAS|<10; trial diffusivity increase to test attenuation; peak width is not measured here",
            "category": "routing"
        })

    # Matched peak height low, scored total flow near observation → diffusivity trial
    if peak_mag_bias is not None and pbias is not None and peak_mag_bias < -20.0 and abs(pbias) < 10.0:
        recs.append({
            "param": "diffusivity", "direction": "decrease", "magnitude": "small",
            "confidence": 0.7,
            "reason": f"Matched-peak height bias={peak_mag_bias:.6g}%<-20 and |PBIAS|<10; trial diffusivity decrease to test attenuation; peak width is not measured here",
            "category": "routing"
        })

    # Sort by confidence × severity
    severity_weight = 1.0 + severity_score  # [1.0, 2.0]
    for rec in recs:
        rec["priority"] = rec["confidence"] * severity_weight

    recs.sort(key=lambda r: r["priority"], reverse=True)

    return recs[:6]


# ============================================================================
# Step 6: Improvement trend
# ============================================================================

def _assess_trend(nse: float, prev_metrics: Optional[Dict]) -> str:
    """Compare the current NSE with the supplied previous record."""
    if prev_metrics is None:
        return "stagnant"
    prev_nse = _safe_float(prev_metrics.get("NSE"), None)
    if prev_nse is None or nse is None:
        return "unknown"
    if prev_nse == -999 or nse == -999:
        return "stagnant"  # The finite failure sentinel does not establish a trend.
    delta = nse - prev_nse
    if delta > 0.005:
        return "improving"
    elif delta < -0.005:
        return "declining"
    else:
        return "stagnant"
